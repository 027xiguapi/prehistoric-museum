伶盗龙是恐龙里的“小个子猎人”。它生活在晚白垩世的沙漠地区，体型和一只火鸡差不多大，但动作敏捷、智慧而警觉。它可能披着羽毛，是驰龙类中很有代表性的一位。电影里那些高大、没羽毛的“迅猛龙”，其实和真实的伶盗龙差别很大，我们正好借这个机会认识真正的它。

